CREATE TABLE IF NOT EXISTS harddisk_Pending (
    id INT AUTO_INCREMENT PRIMARY KEY,
    pending_no VARCHAR(50) NOT NULL COMMENT 'เลขที่รายการรอจัดส่ง เช่น PENDING202606020001',
    source_no INT NULL COMMENT 'ลำดับจากไฟล์ Excel',
    hdd_serial VARCHAR(100) NULL COMMENT 'Serial HDD / Barcode HDD',
    main_branch_code VARCHAR(20) NOT NULL COMMENT 'รหัสสาขาใหญ่',
    main_branch_name VARCHAR(255) NULL COMMENT 'ชื่อสาขาใหญ่',
    branch_code VARCHAR(20) NULL COMMENT 'รหัสสาขาย่อย ถ้ามี',
    branch_name VARCHAR(255) NOT NULL COMMENT 'ชื่อสาขาที่ต้องการจัดส่ง',
    status ENUM('pending_scan','matched','shipped','cancelled') NOT NULL DEFAULT 'matched' COMMENT 'matched=มี SN_HDD แล้ว รอจัดส่ง',
    requested_by VARCHAR(100) NULL COMMENT 'ผู้รับงาน/ผู้บันทึกจากไฟล์',
    requested_at DATETIME NOT NULL COMMENT 'วันที่ลงรายการจากไฟล์',
    matched_by VARCHAR(100) NULL COMMENT 'ผู้จับคู่ HDD',
    matched_at DATETIME NULL COMMENT 'วันที่จับคู่ HDD',
    remark TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL DEFAULT NULL,
    deleted_at DATETIME NULL,
    UNIQUE KEY uk_pending_no (pending_no),
    UNIQUE KEY uk_hdd_serial_active (hdd_serial),
    INDEX idx_main_branch_code (main_branch_code),
    INDEX idx_branch_code (branch_code),
    INDEX idx_branch_name (branch_name),
    INDEX idx_status (status),
    INDEX idx_requested_at (requested_at),
    INDEX idx_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;



INSERT INTO harddisk_Pending (
    pending_no,
    source_no,
    hdd_serial,
    main_branch_code,
    main_branch_name,
    branch_code,
    branch_name,
    status,
    requested_by,
    requested_at,
    matched_by,
    matched_at,
    remark,
    created_at
)
SELECT
    CONCAT('PENDING', DATE_FORMAT(t.requested_at, '%Y%m%d'), LPAD(t.source_no, 4, '0')) AS pending_no,
    t.source_no,
    t.hdd_serial,
    t.main_branch_code,
    t.main_branch_name,
    NULL AS branch_code,
    t.branch_name,
    'matched' AS status,
    t.requested_by,
    t.requested_at,
    t.requested_by AS matched_by,
    t.requested_at AS matched_at,
    'นำเข้าจากไฟล์ Excel รายงาน HDD ที่ส่งให้สาขาแล้ว_2.xlsx' AS remark,
    NOW() AS created_at
FROM tmp_harddisk_pending_import t
WHERE NOT EXISTS (
    SELECT 1
    FROM harddisk_Pending p
    WHERE p.deleted_at IS NULL
      AND (
            (p.hdd_serial IS NOT NULL AND t.hdd_serial IS NOT NULL AND p.hdd_serial = t.hdd_serial)
            OR (p.main_branch_code = t.main_branch_code AND p.branch_name = t.branch_name AND p.status IN ('pending_scan','matched'))
          )
);

DROP TEMPORARY TABLE IF EXISTS tmp_harddisk_pending_import;

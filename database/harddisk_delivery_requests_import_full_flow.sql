-- 1) Import เข้า harddisk_delivery_requests
INSERT INTO harddisk_delivery_requests (
    request_no,
    main_branch_code,
    branch_code,
    branch_name,
    request_reason,
    remark,
    status,
    requested_by,
    requested_at,
    matched_by,
    matched_at,
    created_at
)
SELECT
    t.request_no,
    t.main_branch_code,
    t.branch_code,
    t.branch_name,
    'นำเข้ารายการ HDD รอจัดส่ง' AS request_reason,
    CONCAT(
        'นำเข้าจากไฟล์ Excel รายงาน HDD ที่ส่งให้สาขาแล้ว_2.xlsx',
        ' | ลำดับ: ', IFNULL(t.source_no, '-'),
        ' | SN_HDD: ', IFNULL(t.hdd_serial, '-'),
        ' | ชื่อสาขาใหญ่: ', IFNULL(t.main_branch_name, '-')
    ) AS remark,
    'matched' AS status,
    IFNULL(t.requested_by, 'Import Excel') AS requested_by,
    t.requested_at,
    IFNULL(t.requested_by, 'Import Excel') AS matched_by,
    t.requested_at AS matched_at,
    NOW() AS created_at
FROM tmp_hdd_delivery_requests_import t
WHERE NOT EXISTS (
    SELECT 1
    FROM harddisk_delivery_requests r
    WHERE r.deleted_at IS NULL
      AND (
            r.request_no = t.request_no
            OR (
                r.branch_code = t.branch_code
                AND r.status IN ('pending_scan','matched')
            )
          )
);

-- 2) Preserve SN_HDD ในคลัง harddisk_inventory
INSERT INTO harddisk_inventory (
    hdd_serial,
    status,
    remark,
    created_by,
    created_at
)
SELECT
    t.hdd_serial,
    'reserved' AS status,
    CONCAT('นำเข้าจากไฟล์ Excel และจับคู่กับคำขอ ', t.request_no) AS remark,
    IFNULL(t.requested_by, 'Import Excel') AS created_by,
    NOW() AS created_at
FROM tmp_hdd_delivery_requests_import t
WHERE t.hdd_serial IS NOT NULL
  AND t.hdd_serial <> ''
  AND NOT EXISTS (
      SELECT 1
      FROM harddisk_inventory inv
      WHERE inv.deleted_at IS NULL
        AND inv.hdd_serial = t.hdd_serial
  );

-- 3) ผูก Serial HDD กับคำขอใน harddisk_request_items
INSERT INTO harddisk_request_items (
    request_id,
    hdd_inventory_id,
    hdd_serial,
    scan_status,
    scanned_by,
    scanned_at,
    created_at
)
SELECT
    r.id AS request_id,
    inv.id AS hdd_inventory_id,
    t.hdd_serial,
    'matched' AS scan_status,
    IFNULL(t.requested_by, 'Import Excel') AS scanned_by,
    t.requested_at AS scanned_at,
    NOW() AS created_at
FROM tmp_hdd_delivery_requests_import t
INNER JOIN harddisk_delivery_requests r
    ON r.request_no = t.request_no
LEFT JOIN harddisk_inventory inv
    ON inv.hdd_serial = t.hdd_serial
   AND inv.deleted_at IS NULL
WHERE t.hdd_serial IS NOT NULL
  AND t.hdd_serial <> ''
  AND NOT EXISTS (
      SELECT 1
      FROM harddisk_request_items item
      WHERE item.request_id = r.id
        AND item.hdd_serial = t.hdd_serial
  );

DROP TEMPORARY TABLE IF EXISTS tmp_hdd_delivery_requests_import;
